-- | The freshness case for the files in @ts-src/src/generated/@
-- (@docs/wasm-frontend-unified-plan.md@, 0.2), each committed file against
-- what a test module computes for it, since @make build-ts@ bundles the
-- committed copies as they stand, and the writers the test modules compute
-- them with. None in a browser build, which runs under @make test-wasm@,
-- away from the files.
module FreshnessCase
  ( freshnessOptions
#ifndef USE_BROWSER
  , freshnessCase, generatedHeader, jsonDocument, jsonObject, jsonString
  , jsonBool
#endif
  ) where

import Prelude ()

import Game.LambdaHack.Core.Prelude

import Data.Proxy (Proxy (..))
import Test.Tasty.Options

#ifndef USE_BROWSER
import qualified Data.ByteString as BS
import qualified Data.Text as T
import qualified Data.Text.Encoding as T
import           System.Directory (doesFileExist)
import           Test.Tasty
import           Test.Tasty.HUnit hiding (assert)
import           Text.Printf (printf)
#endif

-- | The freshness case's switch, @--regenerate@, under which it rewrites
-- the committed files rather than comparing them.
newtype Regenerate = Regenerate Bool

instance IsOption Regenerate where
  defaultValue = Regenerate False
  parseValue = fmap Regenerate . safeReadBool
  optionName = return "regenerate"
  optionHelp = return "Rewrite the files in ts-src/src/generated/"
  optionCLParser = flagCLParser Nothing (Regenerate True)

-- | The options the freshness case reads, for the suite's ingredients.
freshnessOptions :: [OptionDescription]
freshnessOptions = [Option (Proxy :: Proxy Regenerate)]

#ifndef USE_BROWSER
-- | The freshness case of one file, given the test module computing it.
freshnessCase :: FilePath -> FilePath -> Text -> TestTree
freshnessCase source name content = askOption $ \(Regenerate regenerate) ->
  testCase ("generated " ++ name ++ " is fresh") $ do
    -- Relative to the directory the .cabal file is in, where cabal runs the
    -- suite, and which the SDL fontset cases rely on too.
    let path = "ts-src/src/generated/" ++ name
        bytes = T.encodeUtf8 content
    exists <- doesFileExist path
    committed <- if exists then Just <$> BS.readFile path else return Nothing
    if | committed == Just bytes -> return ()
       | regenerate -> BS.writeFile path bytes
       | otherwise ->
         assertFailure $ path ++ " differs from what " ++ source
                         ++ " computes; rewrite it with"
                         ++ " cabal test --test-options=--regenerate"

-- | The header of a TypeScript file the given test module generates.
generatedHeader :: FilePath -> [Text]
generatedHeader source =
  [ "// Generated by the freshness case in test/" <> T.pack source <> ", which"
  , "// fails while this file differs from what it computes; rewrite it with"
  , "// cabal test --test-options=--regenerate, not by hand."
  ]

-- | A JSON file of named arrays, one item to a line, that the given test
-- module generates.
jsonDocument :: FilePath -> [(Text, [Text])] -> Text
jsonDocument source arrays = T.unlines $
  [ "{"
  , "  \"source\": "
    <> jsonString ("test/" <> T.pack source <> ", the freshness case")
    <> "," ]
  ++ intercalate ["  ],"] (map array arrays)
  ++ [ "  ]"
     , "}" ]
 where
  array (name, items) =
    ("  " <> jsonString name <> ": [")
    : zipWith (\item comma -> "    " <> item <> comma)
              items (replicate (length items - 1) "," ++ [""])

jsonObject :: [(Text, Text)] -> Text
jsonObject fields =
  "{" <> T.intercalate ", " [jsonString k <> ": " <> v | (k, v) <- fields]
  <> "}"

-- | A JSON string, kept ASCII by escaping everything else.
jsonString :: Text -> Text
jsonString t = "\"" <> T.concatMap escape t <> "\""
 where
  escape c
    | c == '"' || c == '\\' = T.pack ['\\', c]
    | c >= ' ' && c <= '~' = T.singleton c
    | otherwise = assert (fromEnum c <= 0xFFFF) $
                    T.pack $ printf "\\u%04x" (fromEnum c)

jsonBool :: Bool -> Text
jsonBool b = if b then "true" else "false"
#endif
