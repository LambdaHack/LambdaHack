// Runs a GHC wasm32-wasi *command* binary (built the normal way, with a
// plain `_start` -- not a reactor) that also needs GHC's JSFFI glue.
//
// `wasmtime` alone supplies the wasi_snapshot_preview1 import, but not the
// extra ghc_wasm_jsffi import that GHC's JS FFI needs; that import can only
// be satisfied by an actual JS host. This script provides one via Node,
// wiring things up the way the GHC User's Guide's wasm backend chapter
// describes:
// https://downloads.haskell.org/ghc/latest/docs/users_guide/wasm.html
//
// It also stubs the page globals the build's `foreign import javascript`
// declarations call into, where the browser has the page's loader and script
// tags supply them: an in-memory localStorage, the real LZString (from
// node_modules, so a save goes through the compression it ships with), an
// lhSubmitFrame that records each frame, an lhSubmitOverlays that records
// each frame's overlays, an lhConfigure that records each startup payload and
// an lhPrintScreen that records each screenshot's name. The stubs and the
// instantiation are exported, so that run-wasm-game.mjs, which drives the game
// reactor, installs these and not a copy, and so are a sleep and a polling
// wait, which page-gate.mjs shares too.
//
// Usage: node run-wasm-test.mjs <foo.wasm> <ghc_wasm_jsffi.mjs> [args...]
//   <ghc_wasm_jsffi.mjs> is generated by post-link.mjs, e.g.:
//     ~/.ghc-wasm/wasm32-wasi-ghc/lib/post-link.mjs --input foo.wasm --output ghc_wasm_jsffi.mjs
//   lz-string comes from `npm ci` in this directory, which `make test-wasm`
//   runs. Exit status is the binary's, or 2 when the run did not happen.

import { existsSync, readFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Whether `cond`, which may return a promise, comes to hold within `ms`,
// asked every `step` ms, the first time after one step.
export async function waitFor(cond, ms, step = 50) {
  const end = Date.now() + ms;
  do {
    await sleep(step);
    if (await cond()) return true;
  } while (Date.now() < end);
  return false;
}

// Exit 2 unless the two files the run needs exist.
export function requireFiles(usage, wasmPath, jsffiPath) {
  if (!wasmPath || !jsffiPath) {
    console.error(usage);
    process.exit(2);
  }
  for (const p of [wasmPath, jsffiPath]) {
    if (!existsSync(p)) {
      console.error(`${basename(process.argv[1])}: no such file: ${p}`);
      process.exit(2);
    }
  }
}

// An in-memory stand-in for the browser's localStorage, with the methods
// WasmFile.hs calls; getItem returns null for an absent key, as the
// browser's does, which WasmFile.hs's presence check relies on. setItem
// refuses a key under quotaExceeded/ with the error a full browser storage
// throws, for the suite's case of a refused write.
function memoryStorage() {
  const items = new Map();
  return {
    getItem: (k) => (items.has(String(k)) ? items.get(String(k)) : null),
    setItem: (k, v) => {
      if (String(k).startsWith("quotaExceeded/")) {
        throw new DOMException(
          "The quota has been exceeded.",
          "QuotaExceededError",
        );
      }
      items.set(String(k), String(v));
    },
    removeItem: (k) => {
      items.delete(String(k));
    },
    clear: () => {
      items.clear();
    },
    key: (i) => [...items.keys()][i] ?? null,
    get length() {
      return items.size;
    },
  };
}

// Install the page globals; call before the instance runs. `memoryOf`
// returns the instance's linear memory, which exists only once the module is
// instantiated. lhSubmitFrame reads each frame's cells at the address it is
// given and pushes onto globalThis.lhSubmitFrameCalls the frame's size, its
// first cell word and an FNV-1a-style hash of its cell words, keeping a copy of
// the cells in globalThis.lhLastFrame; a size reaching past the memory throws
// instead. lhSubmitOverlays pushes onto globalThis.lhSubmitOverlaysCalls the
// width it is given, the words it reads at the address given and the count
// of frames submitted before it. lhConfigure parses its JSON, as the page's
// loader does, and pushes onto globalThis.lhConfigureCalls the payload and
// the count of frames submitted before it, and lhPrintScreen pushes onto
// globalThis.lhPrintScreenCalls the name it is given and the same count.
export async function installStubs(memoryOf) {
  let LZString;
  try {
    ({ default: LZString } = await import("lz-string"));
  } catch (e) {
    console.error(
      `${basename(process.argv[1])}: cannot load lz-string, ` +
        `which npm ci in ts-src installs: ${e.message}`,
    );
    process.exit(2);
  }
  Object.defineProperty(globalThis, "localStorage", {
    value: memoryStorage(),
    configurable: true,
    writable: true,
  });
  globalThis.LZString = LZString;
  const calls = [];
  globalThis.lhSubmitFrameCalls = calls;
  globalThis.lhSubmitFrame = (addr, w, h) => {
    const cells = new DataView(memoryOf().buffer, addr, 4 * w * h);
    const words = new Uint32Array(w * h);
    let hash = 0x811c9dc5;
    for (let i = 0; i < w * h; i++) {
      words[i] = cells.getUint32(4 * i, true);
      hash = Math.imul(hash ^ words[i], 0x01000193) >>> 0;
    }
    calls.push({ w, h, first: words[0], hash });
    globalThis.lhLastFrame = { w, h, words };
  };
  const overlays = [];
  globalThis.lhSubmitOverlaysCalls = overlays;
  globalThis.lhSubmitOverlays = (addr, len, w) => {
    const cells = new DataView(memoryOf().buffer, addr, 4 * len);
    const words = Array.from({ length: len }, (_, i) =>
      cells.getUint32(4 * i, true),
    );
    overlays.push({ w, words, frames: calls.length });
  };
  const configures = [];
  globalThis.lhConfigureCalls = configures;
  globalThis.lhConfigure = (json) => {
    configures.push({ payload: JSON.parse(json), frames: calls.length });
  };
  const prints = [];
  globalThis.lhPrintScreenCalls = prints;
  globalThis.lhPrintScreen = (name) => {
    prints.push({ name, frames: calls.length });
  };
}

// Instantiate the binary at `wasmPath` under `wasi`, with the JSFFI glue
// at `jsffiPath`, exiting 2 where either cannot be loaded, compiled or
// linked. The glue needs the instance's own exports (mainly `memory`) to
// implement ghc_wasm_jsffi, but imports have to be supplied before an
// instance exists, so the knot is tied with a plain object filled in right
// after instantiation.
export async function instantiate(wasmPath, jsffiPath, wasi) {
  const exportsPlaceholder = {};
  try {
    const { default: makeJsffiImports } = await import(
      pathToFileURL(resolve(jsffiPath)).href
    );
    const { instance } = await WebAssembly.instantiate(readFileSync(wasmPath), {
      wasi_snapshot_preview1: wasi.wasiImport,
      ghc_wasm_jsffi: makeJsffiImports(exportsPlaceholder),
    });
    Object.assign(exportsPlaceholder, instance.exports);
    return instance;
  } catch (e) {
    console.error(
      `${basename(process.argv[1])}: cannot instantiate ${wasmPath}` +
        ` with ${jsffiPath}: ${e}`,
    );
    process.exit(2);
  }
}

if (import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const [, , wasmPath, jsffiPath, ...extraArgs] = process.argv;
  requireFiles(
    "usage: node run-wasm-test.mjs <foo.wasm> <ghc_wasm_jsffi.mjs> [args...]",
    wasmPath,
    jsffiPath,
  );

  // Imported here and not above, since node:wasi warns of its experimental
  // status on import and page-gate.mjs imports this module for waitFor.
  const { WASI } = await import("node:wasi");
  const wasi = new WASI({
    version: "preview1",
    // Haskell's getArgs excludes argv[0], so this only affects things that
    // read the program name directly (getProgName, --help banners); use a
    // short name instead of the full build-tree path for those.
    args: [basename(wasmPath), ...extraArgs],
    env: process.env,
    // GHC's RTS init (hs_init_ghc) does a chdir to an absolute host path
    // during startup (seemingly derived from PWD/argv0), and WASI only lets
    // that resolve through a preopened directory. wasmtime doesn't grant
    // filesystem access by default either (its own docs show `wasmtime run
    // --mapdir /::$PWD` is needed for RTS features that touch the
    // filesystem). This only ever runs a locally built test binary, not
    // untrusted code, so preopening everything is simpler than guessing
    // exactly which path the RTS wants.
    preopens: { "/": "/" },
    returnOnExit: true,
  });

  let instance;
  await installStubs(() => instance.exports.memory);
  instance = await instantiate(wasmPath, jsffiPath, wasi);

  // The test-suite is a plain exitcode-stdio-1.0 executable (a WASI command,
  // exporting `_start`), not a reactor, so run it the same way wasmtime would
  // and propagate its exit code -- `make` needs this to notice test failures.
  process.exitCode = wasi.start(instance);
}
